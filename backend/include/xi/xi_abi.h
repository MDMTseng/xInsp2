/* ------------------------------------------------------------------ */
/* ABI version — bumped on any semantic change to the surfaces       */
/* below. Plugins compiled against version N require a host with     */
/* version >= N (forward compatible — newer host runs older          */
/* plugin), but a host running a plugin compiled against a newer     */
/* version than itself may see null fn pointers in xi_host_api.      */
/*                                                                    */
/* The plugin loader gates on this: a plugin's xi_plugin_abi_version */
/* export (generated by XI_PLUGIN_IMPL) is checked against the       */
/* host's XI_ABI_VERSION and the plugin is refused if it asks for a  */
/* newer ABI than the host provides.                                  */
/*                                                                    */
/* Current version history:                                           */
/*   1 — initial frozen surface (image pool, trigger bus, SHM [fields  */
/*       retained for layout stability; SHM removed 2026-05, always  */
/*       null on current hosts], host api with read_image_file).     */
/*   2 — + emit_resource (emit/fetch resource store). Additive at the */
/*       struct tail, so v1 plugins keep working unchanged.          */
/*   3 — + in-process doc pass-by-pointer (γ): xi_record.doc /        */
/*       xi_record_out.out_doc carry a borrowed/host-owned           */
/*       yyjson_mut_doc* so an in-process call skips the JSON         */
/*       serialize round-trip; doc_chunk_* host allocator backs       */
/*       host-owned docs; the xi_yyjson_abi() plugin export gates it  */
/*       on a matching yyjson layout. All additive at the tail; when  */
/*       the doc pointer is null (older plugin / mismatch / cross-    */
/*       process) the data/len JSON path is used exactly as in v2.    */
/*   4 — + doc_retain/doc_release/doc_refcount (γ-4): a host-side     */
/*       refcount for a yyjson_mut_doc handed across the ABI,         */
/*       mirroring image_addref/release. Lets a doc pointer be held   */
/*       by more than one side (host adopting a doc a plugin still    */
/*       caches; a plugin caching its borrowed input) with no deep    */
/*       copy; doc_refcount lets the adopter learn if it is the sole  */
/*       side. Additive at the tail; null on a pre-v4 host ⇒ callers  */
/*       fall back to the v3 deep-copy / serialize behaviour.         */
/*   5 — + emit_trigger_record: emit_trigger that also carries a       */
/*       JSON metadata doc, by handing the host a whole xi_record      */
/*       (images + data/len + doc) instead of a bare image array.      */
/*       The metadata travels with the event on the trigger bus —      */
/*       correlated through the same policy as the frames — and is      */
/*       read script-side via current_trigger().meta(). It is the      */
/*       routing/context channel the bare emit_trigger lacked          */
/*       (command id, recipe, lane hint).                              */
/*                                                                     */
/*       Zero-serialize: rec->doc (a HOST-OWNED yyjson_mut_doc*, built */
/*       via doc_chunk_*) is carried across the async dispatch by      */
/*       POINTER, refcounted through doc_retain/doc_release — exactly  */
/*       as image handles ride the ImagePool refcount. A plugin-owned  */
/*       bare doc must NOT be passed (its free can't be reconciled);   */
/*       the SDK emit() helper builds a host-owned record. Only the    */
/*       recorder serializes, and only when persisting to disk.        */
/*                                                                     */
/*       Additive at the tail; emit_trigger is exactly                 */
/*       emit_trigger_record with empty metadata, so a pre-v5 host     */
/*       (the pointer is null) just loses the metadata, never the      */
/*       frames.                                                       */
/*   6 — Dispatch model collapsed to ONE plugin verb: emit_trigger_    */
/*       record renamed `emit_record(emitter, id, rec, ts)` (stage +   */
/*       dispatch a record). The trigger bus + correlation policies     */
/*       (Any/AllRequired/LeaderFollowers) and the host record/replay  */
/*       are gone — multi-camera sync is now a gathering plugin (one    */
/*       record, N images) and replay is a buffer-replay plugin.       */
/*       `emit_trigger`, `emit_resource`, `fetch_resource`,            */
/*       `fetch_image`, `emit_dispatch` are RETIRED and REMOVED in the */
/*       dispatch cleanup (no v4 binary compat kept — every plugin     */
/*       rebuilds against v6). A source must now use emit_record. The   */
/*       script reads the dispatched record via current_trigger().     */
/*       image()/.meta(); cmd:run injects the same way for headless    */
/*       tests. See internals/dispatch.md.                             */
/*   7 — + frame-perfect config swap: two OPTIONAL plugin exports,      */
/*       xi_plugin_prepare(inst, def_json, folder) and                 */
/*       xi_plugin_commit(inst). prepare() loads heavy assets into a    */
/*       plugin-internal BACKGROUND staging slot (the live config keeps  */
/*       running); commit() atomically swaps staging -> live. The host  */
/*       calls prepare OUTSIDE its per-instance serialization gate (it  */
/*       runs concurrent with process(), so the load doesn't stall the  */
/*       pipeline) — a plugin only gets this by opting in with the      */
/*       XI_PLUGIN_STAGED macro, whose contract is "prepare touches the */
/*       staging slot ONLY, never live state". commit runs gated. Both  */
/*       are resolved via GetProcAddress: a plugin without them falls   */
/*       back to gated set_def (prepare) / no-op (commit), so simple    */
/*       plugins need neither. These are PLUGIN exports (host->plugin), */
/*       not xi_host_api fields, so they don't shift any struct — an    */
/*       older host simply never calls them. The host pairs prepare     */
/*       with commit_group (a drain-barrier) for frame-perfect group    */
/*       switches. See roadmap/config-bundles-and-orchestration.md.     */
/* ------------------------------------------------------------------ */
/*   8 — + emit_binary (push an opaque binary frame straight to WS clients).      */
/*   9 — + compress_image (host JPEG-encode + content-addressed cache).            */
/*  10 — + get_interface(id, version): the CLAP-style capability-query door.       */
/*       This is the LAST legal monolith append (core_fix_plan.md §12 Phase 1):    */
/*       the v9 prefix is FROZEN (ADR-001) — v10 == v9 + one appended pointer at   */
/*       the struct tail. The host registers the entire current table as           */
/*       get_interface("xi.legacy", 9) and carves frozen per-capability interfaces */
/*       (xi.preview@1, …) behind the same door; old plugins, which never see this */
/*       field, are completely unaffected. From here, capabilities evolve as       */
/*       segregated, independently-frozen interfaces rather than monolith appends. */
/* ------------------------------------------------------------------ */
/*  11 — RETIRE THE MONOLITH (core_fix_plan.md §12 Phase 4, "大破大立"). A         */
/*       DELIBERATE, USER-AUTHORIZED MAJOR ABI BREAK (not additive):               */
/*         (a) the five dead shm_* stubs (always null since the 2026-05 process-   */
/*             isolation removal) are DELETED from xi_host_api — every field after */
/*             instance_folder shifts down 5 pointers (40 bytes);                  */
/*         (b) get_interface("xi.legacy", 9) is NO LONGER PUBLISHED — the whole-   */
/*             table legacy view is retired. The carved interfaces (xi.imaging/    */
/*             doc/emit/log/preview@1) remain the capability path; the struct      */
/*             fields (minus shm) remain for direct callers;                       */
/*         (c) XI_ABI_MIN_COMPAT is raised 6 → 11, so every pre-v11 plugin (which  */
/*             sees the old shm-bearing layout) is REFUSED at load rather than     */
/*             handed a mis-offset table. All in-tree plugins rebuild against v11. */
/*       The v11 layout is the NEW frozen baseline — the ADR-001 freeze discipline */
/*       resumes here (test_abi_freeze.cpp is re-snapshot to v11).                 */
/* ------------------------------------------------------------------ */
#define XI_ABI_VERSION 11  /* v9: + compress_image; v10: + get_interface; v11: shm_* removed, xi.legacy retired */

/* Oldest plugin ABI the host loads; bump on every breaking xi_host_api layout
 * change. Raised 6 → 11 in Phase 4: removing the shm_* block reshuffles offsets,
 * so a pre-v11 plugin's compiled-in table view no longer matches — it must be
 * refused (authorized break; all first-party plugins rebuild against v11). */
#define XI_ABI_MIN_COMPAT 11

/* Expected sizeof(xi_host_api) for the layout guard below (see the ABI LAYOUT
 * GUARD note after the struct). Bump together with XI_ABI_VERSION on any layout
 * change. 64-bit host (all function pointers). */
#define XI_ABI_EXPECTED_SIZE 176  /* 64-bit: 22 function pointers * 8 bytes (v10's 27 − 5 shm_*) */

/* ------------------------------------------------------------------ */
/* Image handle — opaque reference to a refcounted image in the host  */
/* ------------------------------------------------------------------ */

typedef uint64_t xi_image_handle;
#define XI_IMAGE_NULL 0

/* ------------------------------------------------------------------ */
/* Trigger ID — 128-bit identifier for a single inspection event.     */
/* Sources tag every emitted frame with one. Frames sharing a tid are */
/* correlated (e.g., synchronized multi-camera capture). The host's   */
/* TriggerBus groups them and dispatches the script once per tid.     */
/* ------------------------------------------------------------------ */

typedef struct { uint64_t hi; uint64_t lo; } xi_trigger_id;

#ifdef __cplusplus
#define XI_TRIGGER_NULL (xi_trigger_id{0, 0})
#else
#define XI_TRIGGER_NULL ((xi_trigger_id){0, 0})
#endif

static inline int xi_trigger_id_eq(xi_trigger_id a, xi_trigger_id b) {
    return a.hi == b.hi && a.lo == b.lo;
}
static inline int xi_trigger_id_is_null(xi_trigger_id a) {
    return a.hi == 0 && a.lo == 0;
}

