def load_decls() -> list[dict]:
    decls = []
    for p in sorted(DECLS.glob("*.decl.json")):
        decls.append(json.loads(p.read_text(encoding="utf-8")))
    return decls


def render(decl: dict) -> dict[str, str]:
    """{filename: content} for one decl. Deterministic.

    Two artifacts are conditional, so the generator never emits a file that would
    be a lie about what it can express:

      * `_io.gen.h` is SKIPPED when the decl sets `"handwritten_io": true`. Some
        plugins' control surface is outside the constrained typed-field family the
        decl governs (json_source's open-schema raw-JSON builders + Patch shape;
        config_swap_probe's get_status reply extractor; synced_stereo's derived
        has_both()/defaulted fire()). Their `_io.h` stays hand-written — the
        generator owns the KEY contract (guard 1, `_keys.gen.h`) for them but not
        the bespoke I/O veneer. See contract/codegen/README.md (swap-in) and the
        codegen-gap note in docs/new_gen/08.
      * `_schema.gen.h` is SKIPPED when the plugin declares no flat frame slots
        (a source with no `output_frame`): an empty FrameSchema is noise, nothing
        adopts it, and it would never be compiled.
    """
    plugin = decl["plugin"]
    skip: set[str] = set()
    if decl.get("handwritten_io"):
        skip.add("_io.gen.h")
    if not frame_slot_keys(decl):
        skip.add("_schema.gen.h")
    return {plugin + suffix: fn(decl)
            for suffix, fn in ARTIFACTS.items() if suffix not in skip}


def generate(out_dir: Path) -> list[Path]:
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for decl in load_decls():
        for name, content in render(decl).items():
            path = out_dir / name
            path.write_text(content, encoding="utf-8", newline="\n")
            written.append(path)
    return written


def check(out_dir: Path) -> int:
    """Regenerate into a tmp dir, diff against the committed out_dir. Non-zero if
    any committed artifact is stale (the generator is not deterministic-idempotent
    against what is committed)."""
    import tempfile
    stale = []
    with tempfile.TemporaryDirectory() as td:
        tmp = Path(td)
        generate(tmp)
        for fresh in sorted(tmp.iterdir()):
            committed = out_dir / fresh.name
            if not committed.exists():
                stale.append(f"{fresh.name} (missing from {out_dir})")
            elif committed.read_text(encoding="utf-8") != fresh.read_text(encoding="utf-8"):
                stale.append(f"{fresh.name} (differs from committed)")
    if stale:
        print("codegen STALE — regenerate with `python contract/codegen/gen_contract.py`:")
        for s in stale:
            print(f"  - {s}")
        return 1
    print(f"codegen: committed artifacts in {out_dir} are up to date")
    return 0


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT,
                    help="output directory (default: contract/codegen/generated/plugins)")
    ap.add_argument("--check", action="store_true",
                    help="verify committed artifacts are up to date (no write)")
    args = ap.parse_args()
    if args.check:
        return check(args.out)
    written = generate(args.out)
    print(f"codegen: wrote {len(written)} artifact(s) for "
          f"{len(load_decls())} plugin(s) to {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
